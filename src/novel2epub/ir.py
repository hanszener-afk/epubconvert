"""Format-neutral intermediate representation of a novel.

Front ends (DOCX, PDF) produce these objects; the EPUB writer consumes them.
Neither side knows about the other. Every node may carry a SourceRef so that
diagnostics can point at the exact place in the source document.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum

# --------------------------------------------------------------------------
# Source references


@dataclass(frozen=True, slots=True)
class DocxRef:
    part: str  # e.g. "word/document.xml", "word/footnotes.xml"
    paragraph: int  # zero-based index of w:p within the part
    run: int | None = None

    def __str__(self) -> str:
        where = f"{self.part} paragraph {self.paragraph + 1}"
        return where if self.run is None else f"{where}, run {self.run + 1}"


@dataclass(frozen=True, slots=True)
class PdfRef:
    page: int  # one-based page number
    bbox: tuple[float, float, float, float]  # x0, y0, x1, y1 in PDF points

    def __str__(self) -> str:
        x0, y0, x1, y1 = self.bbox
        return f"page {self.page} at ({x0:.0f}, {y0:.0f})-({x1:.0f}, {y1:.0f})"


@dataclass(frozen=True, slots=True)
class ManualRef:
    """Used by hand-built books in tests."""

    label: str

    def __str__(self) -> str:
        return self.label


SourceRef = DocxRef | PdfRef | ManualRef


# --------------------------------------------------------------------------
# Inline content


@dataclass(slots=True)
class Text:
    text: str


@dataclass(slots=True)
class LineBreak:
    """A soft line break inside a block (DOCX w:br without a type)."""


@dataclass(slots=True)
class Span:
    """Base for formatted inline containers. Use a subclass."""

    children: list[Inline]


@dataclass(slots=True)
class Italic(Span):
    pass


@dataclass(slots=True)
class Bold(Span):
    pass


@dataclass(slots=True)
class SmallCaps(Span):
    pass


@dataclass(slots=True)
class AllCaps(Span):
    """Displayed in capitals; the characters keep the case the author typed."""


@dataclass(slots=True)
class Superscript(Span):
    pass


@dataclass(slots=True)
class Subscript(Span):
    pass


@dataclass(slots=True)
class Link(Span):
    href: str = ""


@dataclass(slots=True)
class NoteRef:
    """Reference to a Note in Book.notes. The marker is generated by the writer."""

    note_id: str


Inline = (
    Text
    | LineBreak
    | Italic
    | Bold
    | SmallCaps
    | AllCaps
    | Superscript
    | Subscript
    | Link
    | NoteRef
)


# --------------------------------------------------------------------------
# Blocks


class Align(Enum):
    START = "start"
    CENTRE = "centre"
    END = "end"


@dataclass(slots=True)
class Paragraph:
    content: list[Inline]
    align: Align = Align.START
    source: SourceRef | None = None


@dataclass(slots=True)
class Heading:
    """A heading inside a section (the section title is Section.title)."""

    content: list[Inline]
    level: int = 2  # 2..6; 1 only in an untitled section, such as a title page's title
    source: SourceRef | None = None


@dataclass(slots=True)
class SceneBreak:
    source: SourceRef | None = None


@dataclass(slots=True)
class BlockQuote:
    blocks: list[Block]
    source: SourceRef | None = None


@dataclass(slots=True)
class Epigraph:
    blocks: list[Block]
    attribution: list[Inline] | None = None
    source: SourceRef | None = None


@dataclass(slots=True)
class Verse:
    """Poetry or song lyrics. Each stanza is a list of lines."""

    stanzas: list[list[list[Inline]]]
    source: SourceRef | None = None


@dataclass(slots=True)
class Image:
    resource_id: str  # key into Book.resources
    alt: str | None  # None means the source had no alt text
    caption: list[Inline] | None = None
    source: SourceRef | None = None


Block = Paragraph | Heading | SceneBreak | BlockQuote | Epigraph | Verse | Image


# --------------------------------------------------------------------------
# Notes, resources, sections, book


class NoteKind(Enum):
    FOOTNOTE = "footnote"
    ENDNOTE = "endnote"


@dataclass(slots=True)
class Note:
    id: str
    kind: NoteKind
    blocks: list[Block]
    source: SourceRef | None = None
    label: str | None = None  # the author's marker (e.g. "*"); None means auto-number


@dataclass(slots=True)
class Resource:
    """A binary resource such as an image. media_type must be EPUB-core."""

    id: str
    media_type: str
    data: bytes


class SectionKind(Enum):
    CHAPTER = "chapter"
    PART = "part"  # a part title page; the chapters after it have depth 1
    PROLOGUE = "prologue"
    EPILOGUE = "epilogue"
    TITLEPAGE = "titlepage"
    HALFTITLE = "halftitle"
    COPYRIGHT = "copyright"
    DEDICATION = "dedication"
    EPIGRAPH = "epigraph"
    FOREWORD = "foreword"
    PREFACE = "preface"
    INTRODUCTION = "introduction"
    ACKNOWLEDGEMENTS = "acknowledgements"
    AFTERWORD = "afterword"
    ABOUT_AUTHOR = "about-author"
    ALSO_BY = "also-by"
    OTHER = "other"


@dataclass(slots=True)
class Section:
    kind: SectionKind
    title: list[Inline] | None
    blocks: list[Block]
    source: SourceRef | None = None
    depth: int = 0  # 1 for a chapter inside a part; nests it in the contents
    # Blocks printed above the title (a quotation set over a chapter heading).
    # Rendered before the title, so the author's order is kept.
    opener: list[Block] = field(default_factory=list)


@dataclass(slots=True)
class Metadata:
    title: str
    authors: list[str]
    language: str  # BCP 47, e.g. "en-GB"
    identifier: str | None = None  # "urn:uuid:..."; filled by metadata.resolve()
    modified: datetime | None = None  # timezone-aware; filled by metadata.resolve()
    subtitle: str | None = None
    publisher: str | None = None
    date: str | None = None  # publication date, W3CDTF (e.g. "2026" or "2026-10-01")
    series: str | None = None
    series_index: str | None = None
    description: str | None = None
    rights: str | None = None
    isbn: str | None = None
    # Accessibility claims are the publisher's to make; these are passed through.
    conforms_to: str | None = None
    certified_by: str | None = None
    accessibility_summary: str | None = None


@dataclass(slots=True)
class Cover:
    resource_id: str
    alt: str


@dataclass(slots=True)
class Style:
    """Layout choices for the book; None leaves the stylesheet's default.

    Lengths are in em, so they scale with the reader's text size. Top and
    bottom margins apply where each chapter starts and ends: margins on every
    page are the reading system's, not the book's.
    """

    side_margin: float | None = None
    top_margin: float | None = None
    bottom_margin: float | None = None
    indent: float | None = None  # first-line indent
    paragraph_gap: float | None = None  # space after each paragraph
    block_paragraphs: bool = False  # no indents, a gap between paragraphs
    line_spacing: float | None = None  # a multiple of the font size, e.g. 1.4


# Allowed ranges for the Style values (em, or a multiple for line spacing).
STYLE_LIMITS = {
    "side_margin": (0.0, 10.0), "top_margin": (0.0, 10.0), "bottom_margin": (0.0, 10.0),
    "indent": (0.0, 5.0), "paragraph_gap": (0.0, 3.0), "line_spacing": (1.0, 3.0),
}  # fmt: skip


@dataclass(slots=True)
class EmbeddedFont:
    """A font file to embed. `slot` says what it is for (see fonts.FONT_SLOTS)."""

    slot: str
    family: str
    italic: bool
    bold: bool
    media_type: str  # font/ttf or font/otf
    data: bytes

    @property
    def extension(self) -> str:
        return self.media_type.removeprefix("font/")


@dataclass(slots=True)
class Book:
    metadata: Metadata
    body: list[Section]
    front: list[Section] = field(default_factory=list)
    back: list[Section] = field(default_factory=list)
    notes: dict[str, Note] = field(default_factory=dict)
    resources: dict[str, Resource] = field(default_factory=dict)
    cover: Cover | None = None
    style: Style = field(default_factory=Style)
    fonts: list[EmbeddedFont] = field(default_factory=list)

    def sections(self) -> list[Section]:
        return [*self.front, *self.body, *self.back]
